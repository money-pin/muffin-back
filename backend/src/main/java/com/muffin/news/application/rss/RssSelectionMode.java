package com.muffin.news.application.rss;

/**
 * RSS 기사 선별 방식. 두 방식의 구현을 모두 두고 설정으로 고른다.
 *
 * <p>카테고리별 선별은 피드마다 따로 평가하므로 하루 전체에서 무엇이 가장 중요한지는 아무도 판단하지 않는다. 통합 선별은 그 문제를
 * 해결하는 대신 특정 카테고리가 0건이 될 수 있다.
 */
public enum RssSelectionMode {
    /** 카테고리별로 따로 평가해 각각 최대 N건을 고른다. 총량이 카테고리 수에 비례해 늘어난다. */
    PER_CATEGORY,
    /** 모든 카테고리 후보를 한 번에 평가해 전체에서 최대 N건을 고른다. 총량이 카테고리 수와 무관하게 고정된다. */
    UNIFIED
}
